create extension if not exists pgcrypto;

create table if not exists public.school_actor_keys (
  id uuid primary key default gen_random_uuid(),
  school_id text not null,
  actor_id text not null,
  actor_name text not null default '',
  actor_role text not null check (actor_role in ('director','teacher','paee')),
  group_name text,
  token_hash text not null unique,
  active boolean not null default true,
  created_at timestamptz not null default now(),
  unique (school_id, actor_id)
);
alter table public.school_actor_keys enable row level security;

create or replace function public.request_actor(requested_school text)
returns jsonb language sql stable security definer set search_path=public as $$
  select jsonb_build_object('id',k.actor_id,'name',k.actor_name,'role',k.actor_role,'group',k.group_name)
  from public.school_actor_keys k
  where k.school_id=requested_school and k.active
    and k.token_hash=encode(digest(coalesce((current_setting('request.headers',true)::jsonb->>'x-school-token'),''),'sha256'),'hex')
  limit 1;
$$;
revoke all on function public.request_actor(text) from public;
grant execute on function public.request_actor(text) to anon,authenticated;

create or replace function public.school_request_authorized(requested_school text)
returns boolean language sql stable security definer set search_path=public as $$
  select public.request_actor(requested_school) is not null;
$$;

create table if not exists public.school_notices (
  id uuid primary key default gen_random_uuid(), school_id text not null,
  title text not null check (length(title) between 1 and 140),
  body text not null check (length(body) between 1 and 2000),
  audience_type text not null default 'all' check (audience_type in ('all','group','teacher')),
  audience_value text, priority text not null default 'normal' check (priority in ('normal','high')),
  created_by text not null, published_at timestamptz not null default now(), expires_at timestamptz
);
create index if not exists idx_school_notices_school_date on public.school_notices(school_id,published_at desc);

create table if not exists public.notice_reads (
  school_id text not null, notice_id uuid not null references public.school_notices(id) on delete cascade,
  teacher_id text not null, read_at timestamptz not null default now(), primary key(notice_id,teacher_id)
);

create table if not exists public.school_messages (
  id uuid primary key default gen_random_uuid(), school_id text not null,
  kind text not null check (kind in ('incident','request')),
  category text not null, group_name text not null, teacher_id text not null, teacher_name text not null default '',
  body text not null check (length(body) between 1 and 800), priority text not null default 'normal' check(priority in ('normal','high')),
  status text not null default 'new' check(status in ('new','received','in_process','resolved','rejected')),
  director_response text, created_at timestamptz not null default now(), updated_at timestamptz not null default now()
);
create index if not exists idx_school_messages_inbox on public.school_messages(school_id,status,created_at desc);

create table if not exists public.communication_audit (
  id bigint generated by default as identity primary key, school_id text not null,
  entity_type text not null, entity_id text not null, action text not null,
  actor_id text not null, actor_role text not null, details jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now()
);
create index if not exists idx_communication_audit_school_date on public.communication_audit(school_id,created_at desc);

create table if not exists public.push_subscriptions (
  id uuid primary key default gen_random_uuid(), school_id text not null, actor_id text not null,
  endpoint text not null, p256dh text not null, auth text not null, user_agent text,
  active boolean not null default true, updated_at timestamptz not null default now(),
  unique(school_id,actor_id,endpoint)
);

