create policy attendance_reports_actor_read on public.attendance_reports for select to anon,authenticated using (
  public.school_request_authorized(school_id) and ((public.request_actor(school_id)->>'role')='director' or ((public.request_actor(school_id)->>'role')='teacher' and (public.request_actor(school_id)->>'group')=group_name))
);
create policy attendance_reports_teacher_insert on public.attendance_reports for insert to anon,authenticated with check (
  public.school_request_authorized(school_id) and (public.request_actor(school_id)->>'role')='teacher' and (public.request_actor(school_id)->>'id')=teacher_id and (public.request_actor(school_id)->>'group')=group_name
);
create policy attendance_reports_teacher_update on public.attendance_reports for update to anon,authenticated using (
  public.school_request_authorized(school_id) and (public.request_actor(school_id)->>'role')='teacher' and (public.request_actor(school_id)->>'id')=teacher_id and (public.request_actor(school_id)->>'group')=group_name
) with check ((public.request_actor(school_id)->>'id')=teacher_id and (public.request_actor(school_id)->>'group')=group_name);

create policy notices_target_read on public.school_notices for select to anon,authenticated using (
  public.school_request_authorized(school_id) and ((public.request_actor(school_id)->>'role')='director' or audience_type='all' or (audience_type='group' and audience_value=(public.request_actor(school_id)->>'group')) or (audience_type='teacher' and audience_value=(public.request_actor(school_id)->>'id')))
);
create policy notices_director_write on public.school_notices for insert to anon,authenticated with check ((public.request_actor(school_id)->>'role')='director' and created_by=(public.request_actor(school_id)->>'id'));

create policy reads_owner_select on public.notice_reads for select to anon,authenticated using ((public.request_actor(school_id)->>'role')='director' or teacher_id=(public.request_actor(school_id)->>'id'));
create policy reads_owner_insert on public.notice_reads for insert to anon,authenticated with check (teacher_id=(public.request_actor(school_id)->>'id'));
create policy reads_owner_update on public.notice_reads for update to anon,authenticated using (teacher_id=(public.request_actor(school_id)->>'id')) with check (teacher_id=(public.request_actor(school_id)->>'id'));

create policy messages_participant_read on public.school_messages for select to anon,authenticated using ((public.request_actor(school_id)->>'role')='director' or teacher_id=(public.request_actor(school_id)->>'id'));
create policy messages_teacher_insert on public.school_messages for insert to anon,authenticated with check ((public.request_actor(school_id)->>'role')='teacher' and teacher_id=(public.request_actor(school_id)->>'id') and group_name=(public.request_actor(school_id)->>'group'));
create policy messages_director_update on public.school_messages for update to anon,authenticated using ((public.request_actor(school_id)->>'role')='director') with check ((public.request_actor(school_id)->>'role')='director');
create policy audit_director_read on public.communication_audit for select to anon,authenticated using ((public.request_actor(school_id)->>'role')='director');
create policy push_owner_select on public.push_subscriptions for select to anon,authenticated using (actor_id=(public.request_actor(school_id)->>'id'));
create policy push_owner_insert on public.push_subscriptions for insert to anon,authenticated with check (actor_id=(public.request_actor(school_id)->>'id'));
create policy push_owner_update on public.push_subscriptions for update to anon,authenticated using (actor_id=(public.request_actor(school_id)->>'id')) with check (actor_id=(public.request_actor(school_id)->>'id'));

create or replace function public.audit_school_change() returns trigger language plpgsql security definer set search_path=public as $$
declare school text:=coalesce(new.school_id,old.school_id); actor jsonb; entity text:=tg_table_name; eid text;
begin actor:=public.request_actor(school);eid:=coalesce(new.id::text,old.id::text);insert into public.communication_audit(school_id,entity_type,entity_id,action,actor_id,actor_role,details) values(school,entity,eid,tg_op,coalesce(actor->>'id','system'),coalesce(actor->>'role','system'),jsonb_build_object('new',to_jsonb(new),'old',to_jsonb(old)));if tg_op='DELETE' then return old;else return new;end if;end;$$;
drop trigger if exists audit_school_notices on public.school_notices;
drop trigger if exists audit_school_messages on public.school_messages;
create trigger audit_school_notices after insert or update or delete on public.school_notices for each row execute function public.audit_school_change();
create trigger audit_school_messages after insert or update or delete on public.school_messages for each row execute function public.audit_school_change();

